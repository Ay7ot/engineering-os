"""Claude Code adapter: neutral source -> ~/.claude (+ ~/.claude.json).

  agents/* (role: subagent) -> <claude_dir>/agents/*.md
      permissions -> disallowedTools + PreToolUse hooks (hooks/eos_guard.py)
  agents/* (role: primary)  -> <claude_dir>/output-styles/eos-lead.md
      ("EngineeringOS Lead" output style, made the default outputStyle in
      <claude_dir>/settings.json unless the user already picked another style)
  skills/*/                 -> <claude_dir>/skills/*/
  commands/*.md             -> <claude_dir>/commands/*.md
  always-on context         -> managed block in <claude_dir>/CLAUDE.md
  engineering-memory MCP    -> user scope (via `claude mcp` when the CLI exists,
                               else merged into <claude_json>)

Names that collide with Claude Code built-ins are prefixed with `eos-`.
"""
import json
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

from adapters.common import (MCP_NAME, Writer, atomic_write_json, grants, load_json,
                             log, write_text_if_changed)

NAME = "claude"
BLOCK_BEGIN = "<!-- BEGIN EngineeringOS (managed by `eng sync-claude`; edits inside this block are overwritten) -->"
BLOCK_END = "<!-- END EngineeringOS -->"
STYLE_FILE = "eos-lead.md"
STYLE_NAME = "EngineeringOS Lead"
GENERATED = "Generated by `eng sync-claude`"
GUARD = Path(__file__).resolve().parent / "hooks" / "eos_guard.py"

# Avoid shadowing Claude Code built-in skills/commands.
SKILL_RENAMES = {"code-review": "eos-code-review", "security-review": "eos-security-review"}
COMMAND_RENAMES = {"review": "eos-review", "debug": "eos-debug"}

# Neutral model tiers -> Claude model aliases (override with targets.claude.model).
TIER_MODELS = {"deep": "opus", "standard": "sonnet", "fast": "haiku"}

TOOL_NOTE = (
    "> Claude Code tool names: read -> Read, glob/list -> Glob, grep -> Grep, "
    "edit -> Edit/Write, bash -> Bash, webfetch -> WebFetch, websearch -> WebSearch, "
    "todowrite -> TodoWrite, task -> Agent, skill -> Skill. "
    "EngineeringOS memory tools are `mcp__engineering-memory__*`."
)


def claude_dir(ctx):
    cfg = ctx.env.get("CLAUDE_CONFIG_DIR")
    return Path(cfg) if cfg else ctx.home / ".claude"


def claude_json(ctx):
    if ctx.options.get("claude_json"):
        return Path(ctx.options["claude_json"])
    cfg = ctx.env.get("CLAUDE_CONFIG_DIR")
    return Path(cfg) / ".claude.json" if cfg else ctx.home / ".claude.json"


def detect(ctx):
    return bool(shutil.which("claude")) or claude_dir(ctx).is_dir()


def q(s):
    """YAML-safe double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(s, ensure_ascii=False)


def rename_refs(text):
    for old, new in SKILL_RENAMES.items():
        # Bare names ("the `code-review` skill") and installed paths
        # ("~/.claude/skills/code-review/"). Source paths (skills/<old>) stay.
        text = re.sub(r"(?<![\w/-])" + re.escape(old) + r"(?![\w-])", new, text)
        text = re.sub(r"(\.claude/skills/)" + re.escape(old) + r"(?![\w-])", r"\g<1>" + new, text)
    for old, new in COMMAND_RENAMES.items():
        text = re.sub(r"(?<![\w-])/" + re.escape(old) + r"(?![\w-])", "/" + new, text)
    return text


# --- translation --------------------------------------------------------------

def _guard_cmd(py, mode, allow=(), deny=(), protect=()):
    parts = [py, str(GUARD), mode]
    for p in allow:
        parts += ["--allow", p]
    for p in deny:
        parts += ["--deny", p]
    for p in protect:
        parts += ["--protect", str(p)]
    return " ".join(shlex.quote(p) for p in parts)


def translate_permissions(perm, py, protect=()):
    """Return (disallowed_tools, [(matcher, command)]). Fails closed via grants()."""
    disallowed, hooks = [], []
    if not isinstance(perm, dict):
        return disallowed, hooks

    edit = perm.get("edit", "allow")
    if isinstance(edit, dict):
        rules = {k: v for k, v in edit.items() if k != "*"}
        allow = [k for k, v in rules.items() if grants(v)]
        deny = [k for k, v in rules.items() if not grants(v)]
        if not grants(edit.get("*", "allow")):
            if allow:
                hooks.append(("Edit|Write|NotebookEdit",
                              _guard_cmd(py, "edit", allow=allow, deny=deny, protect=protect)))
            else:
                disallowed += ["Edit", "Write", "NotebookEdit"]
        elif deny:
            hooks.append(("Edit|Write|NotebookEdit", _guard_cmd(py, "edit", allow=["*"], deny=deny, protect=protect)))
    elif not grants(edit):
        disallowed += ["Edit", "Write", "NotebookEdit"]

    bash = perm.get("bash", "allow")
    if isinstance(bash, dict):
        rules = {k: v for k, v in bash.items() if k != "*"}
        if not grants(bash.get("*", "allow")):
            allow = [k for k, v in rules.items() if grants(v)]
            deny = [k for k, v in rules.items() if not grants(v)]
            if allow:
                # Deny rules are checked before allows in the guard, so a later
                # "npm publish *": deny still blocks under "npm *": allow.
                hooks.append(("Bash", _guard_cmd(py, "bash", allow=allow, deny=deny)))
            else:
                disallowed.append("Bash")
        else:
            deny = [k for k, v in rules.items() if not grants(v)]
            if deny:
                hooks.append(("Bash", _guard_cmd(py, "bash", deny=deny)))
    elif not grants(bash):
        disallowed.append("Bash")

    for key, tool in (("webfetch", "WebFetch"), ("websearch", "WebSearch"), ("task", "Agent")):
        if key in perm and not grants(perm[key]):
            disallowed.append(tool)
    return disallowed, hooks


def model_for(agent):
    return agent.target(NAME).get("model") or TIER_MODELS.get(agent.fm.get("model_tier"), "inherit")


def render_agent(agent, rel_source, py, protect):
    disallowed, hooks = translate_permissions(agent.fm.get("permissions"), py, protect)
    out = ["---", f"name: {agent.name}", f"description: {q(agent.fm['description'])}", f"model: {model_for(agent)}"]
    if disallowed:
        out.append("disallowedTools: " + ", ".join(disallowed))
    if hooks:
        out += ["hooks:", "  PreToolUse:"]
        for matcher, cmd in hooks:
            out += [
                f"    - matcher: {q(matcher)}",
                "      hooks:",
                "        - type: command",
                f"          command: {q(cmd)}",
            ]
    out.append("---")
    out.append(f"<!-- {GENERATED} from {rel_source}. Edit the source, not this file. -->")
    out.append("")
    out.append(TOOL_NOTE)
    out.append("")
    return "\n".join(out) + "\n" + rename_refs(agent.body.lstrip("\n"))


def render_skill(name, skill):
    out = ["---", f"name: {name}", f"description: {q(rename_refs(skill.fm.get('description', name)))}", "---"]
    return "\n".join(out) + "\n" + rename_refs(skill.body)


def render_command(cmd):
    out = ["---", f"description: {q(cmd.fm.get('description', ''))}", "---"]
    return "\n".join(out) + "\n" + rename_refs(cmd.body)


def render_style(primary, rel_source, agents):
    out = [
        "---",
        f"name: {q(STYLE_NAME)}",
        f"description: {q('EngineeringOS Lead: orchestrate specialist subagents, approval gates, persistent engineering memory')}",
        "keep-coding-instructions: true",
        "---",
        f"<!-- {GENERATED} from {rel_source}. Edit the source, not this file. -->",
        "",
        "You are running in the EngineeringOS Lead mode. Delegate with the Agent tool to the EngineeringOS "
        "subagents: " + ", ".join(f"`{a}`" for a in agents) + ". Prefer them over the built-in Explore/Plan "
        "agents when following EngineeringOS workflows.",
        "",
        TOOL_NOTE,
        "",
    ]
    return "\n".join(out) + "\n" + rename_refs(primary.body.strip()) + "\n"


def render_claude_block(engine, data, agents, commands):
    lines = [
        BLOCK_BEGIN,
        "# EngineeringOS",
        "",
        f"@{engine}/PRINCIPLES.md",
        f"@{data}/USER.md",
        "",
        f"- The `{MCP_NAME}` MCP server (`mcp__{MCP_NAME}__*`) is the system of record for project context, ADRs, "
        "research, tasks and state. Claude Code's built-in auto-memory is only for personal working preferences; "
        "durable project knowledge goes to EngineeringOS.",
        "- Project rules: if a repo has `AGENTS.md` but no `CLAUDE.md`, read `AGENTS.md`.",
        "- EngineeringOS subagents: " + ", ".join(f"`{a}`" for a in agents) + ".",
        "- Workflows: " + ", ".join(f"`/{c}`" for c in commands) + ".",
        f"- The orchestration role lives in the `{STYLE_NAME}` output style.",
        BLOCK_END,
    ]
    return "\n".join(lines) + "\n"


# --- config files -------------------------------------------------------------------

def merge_claude_md(path, block):
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    pattern = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END) + r"\n?", re.S)
    if pattern.search(text):
        new = pattern.sub(lambda _: block, text, count=1)
    else:
        new = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    return write_text_if_changed(path, new)


def set_default_style(settings_path):
    """Make the Lead style the default unless the user already chose another."""
    cfg = load_json(settings_path)
    current = cfg.get("outputStyle")
    if current == STYLE_NAME:
        return "already default"
    if current not in (None, "", "default"):
        return f"left your outputStyle {current!r} in place (set it to {STYLE_NAME!r} to use the Lead mode)"
    cfg["outputStyle"] = STYLE_NAME
    atomic_write_json(settings_path, cfg)
    return f"set default outputStyle to {STYLE_NAME!r} in {settings_path}"


def mcp_entry(ctx):
    return {
        "type": "stdio",
        "command": ctx.python,
        "args": [str(ctx.server)],
        "env": {"ENGINEERING_OS_DATA": str(ctx.data)},
    }


def read_mcp(path):
    return load_json(path).get("mcpServers", {}).get(MCP_NAME)


def configure_mcp(path, entry, cli):
    if read_mcp(path) == entry:
        return f"{MCP_NAME} MCP already configured"
    if cli:
        # Let Claude Code write its own config file: no lost-update race with a
        # running instance.
        subprocess.run([cli, "mcp", "remove", "--scope", "user", MCP_NAME], capture_output=True, text=True)
        res = subprocess.run([cli, "mcp", "add-json", "--scope", "user", MCP_NAME, json.dumps(entry)],
                             capture_output=True, text=True)
        if res.returncode == 0:
            return f"configured {MCP_NAME} MCP via `claude mcp add-json` (user scope)"
        log(NAME, f"`claude mcp add-json` failed ({res.stderr.strip() or res.returncode}); editing {path} directly")
    cfg = load_json(path)
    cfg.setdefault("mcpServers", {})[MCP_NAME] = entry
    atomic_write_json(path, cfg)
    if read_mcp(path) != entry:
        sys.exit(f"[eng]   FAIL: {MCP_NAME} entry did not persist in {path}")
    return (f"configured {MCP_NAME} MCP in {path} (backup: *.engineeringos.bak). "
            "If Claude Code was running, restart it, then run 'eng health' to confirm the entry survived")


# --- contract ---------------------------------------------------------------------

def sync(ctx, source):
    cdir = claude_dir(ctx)
    engine = ctx.engine
    # Markdown-only editors (architect) must not rewrite agent definitions, the
    # adapters, or anything imported into every session (PRINCIPLES.md, data/).
    protect = [cdir, engine / "adapters", engine / "agents", engine / "skills", engine / "commands",
               engine / "PRINCIPLES.md", ctx.data]
    w = Writer(cdir, NAME)
    agents, commands = [], []

    for a in source.subagents():
        dest = cdir / "agents" / f"{a.name}.md"
        w.write(dest, render_agent(a, f"agents/{a.path.name}", ctx.python, protect))
        if w.wrote(dest):
            agents.append(a.name)

    for s in source.skills:
        name = SKILL_RENAMES.get(s.name, s.name)
        w.write(cdir / "skills" / name / "SKILL.md", render_skill(name, s))
        for rel, f in s.files:
            w.write(cdir / "skills" / name / rel, f.read_bytes())

    for c in source.commands:
        name = COMMAND_RENAMES.get(c.name, c.name)
        dest = cdir / "commands" / f"{name}.md"
        w.write(dest, render_command(c))
        if w.wrote(dest):
            commands.append(name)

    primaries = source.primary()
    lead = next((p for p in primaries if p.name == "lead"), primaries[0] if primaries else None)
    if lead:
        w.write(cdir / "output-styles" / STYLE_FILE, render_style(lead, f"agents/{lead.path.name}", agents))

    w.finish()
    log(NAME, f"{len(agents)} agents, {len(commands)} commands, skills, output style synced ({w.changed} files changed)")

    if merge_claude_md(cdir / "CLAUDE.md", render_claude_block(engine, ctx.data, agents, commands)):
        log(NAME, f"updated EngineeringOS block in {cdir / 'CLAUDE.md'}")
    if lead:
        log(NAME, set_default_style(cdir / "settings.json"))

    cli = ctx.options.get("claude_cli")
    if cli is None:
        cli = shutil.which("claude") or ""
    log(NAME, configure_mcp(claude_json(ctx), mcp_entry(ctx), cli))


def health(ctx, source):
    cdir, cj = claude_dir(ctx), claude_json(ctx)
    if not detect(ctx):
        print("[eng]   Claude Code: not installed")
        return
    agents = sorted(p.stem for p in (cdir / "agents").glob("*.md") if GENERATED in p.read_text(encoding="utf-8"))
    print(f"[eng]   Claude agents synced: {' '.join(agents) or '(none)'}")
    commands = sorted(p.stem for p in (cdir / "commands").glob("*.md"))
    print(f"[eng]   Claude commands: {' '.join(commands) or '(none)'}")
    md = cdir / "CLAUDE.md"
    has_block = md.exists() and BLOCK_BEGIN in md.read_text(encoding="utf-8")
    print(f"[eng]   Claude CLAUDE.md block: {'present' if has_block else 'missing'}")
    style = (cdir / "output-styles" / STYLE_FILE).is_file()
    try:
        current = load_json(cdir / "settings.json").get("outputStyle") or "default"
    except SystemExit:
        current = "(settings.json unreadable)"
    print(f"[eng]   Claude Lead style: {'present' if style else 'missing'}, default outputStyle: {current}")
    try:
        entry = read_mcp(cj)
    except SystemExit:
        entry = None
    if isinstance(entry, dict) and entry.get("args") and Path(entry["args"][0]).is_file():
        print(f"[eng]   Claude MCP: ok ({MCP_NAME} -> {entry['args'][0]})")
    else:
        print("[eng]   Claude MCP: missing (run 'eng sync-claude')")
